const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const scope={window:{}};
vm.runInNewContext(fs.readFileSync('static/grammar_course.js','utf8'),scope);
const ui=scope.window.LexiGrammar;
const rows=JSON.parse(fs.readFileSync('data/grammar_lessons.json','utf8')).lessons.map((r,i)=>({...r,description:r.summary,number:i+1,question_count:r.questions.length}));
assert.equal(ui.filterLessons(rows,{level:'basic',q:''}).length,16);
assert.equal(ui.filterLessons(rows,{level:'',q:''}).length,36);
assert.equal(ui.filterLessons(rows,{level:'A1',q:'danh tu so nhieu'})[0].id,'a1-plural-nouns');
assert.equal(ui.filterLessons(rows,{level:'B2',q:'danh tu so nhieu'}).length,0);
const data=rows[0],html=ui.lessonHTML(data,'<details>Sources</details>','<form>Graded practice</form>');
assert.match(html,/data-grammar-panel="practice" tabindex="-1" hidden/);
assert.match(html,/data-grammar-panel="lesson"/);
assert.match(html,/<summary>Xem đáp án và cách làm<\/summary>/);
assert.equal((html.match(/class="grammar-explanation"/g)||[]).length,3);
assert.equal((html.match(/data-quiz/g)||[]).length,1);
const evil=structuredClone(data);
evil.teaching.objective='<img src=x onerror=alert(1)>';
evil.teaching.quick_check.answer='<script>bad()</script>';
evil.explanation[0].pattern='<script>bad()</script>';
evil.navigation={next:{id:'bad" onclick="evil',title:'<img src=x>',level:'A1'}};
assert.doesNotMatch(ui.lessonHTML(evil,'',''),/<script>|<img/);
assert.doesNotMatch(ui.lessonHTML(evil,'',''),/" onclick=/);
const advanced=ui.lessonHTML(rows.find(r=>r.level==='C1'),'','<form>Practice</form>');
assert.doesNotMatch(advanced,/undefined|null/);
assert.match(advanced,/data-quiz/);
assert.match(ui.cardsHTML(rows),/Bắt đầu với câu đơn/);
console.log('PASS grammar level/search filters, original lesson content, hidden practice, safe teaching HTML and advanced fallback');

const progressRows=rows.map((r,i)=>({...r,is_read:i<2}));
assert.equal(ui.filterLessons(progressRows,{level:'',q:'',status:'read'}).length,2);
assert.equal(ui.filterLessons(progressRows,{level:'basic',q:'',status:'unread'}).length,14);
assert.equal(ui.filterLessons(progressRows,{level:'B2',q:'',status:'read'}).length,0);
assert.match(ui.cardsHTML(progressRows.slice(0,3)),/✓ Đã đọc/);
assert.match(ui.cardsHTML(progressRows.slice(0,3)),/Chưa đọc/);
assert.match(ui.lessonHTML({...data,is_read:true},'',''),/data-grammar-read="[^"]+" aria-pressed="true"/);
console.log('PASS combined grammar read/level/search filters and explicit read controls');
