const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context={window:{},URL};
vm.runInNewContext(fs.readFileSync('static/academy.js','utf8'),context);
const ui=context.window.LexiAcademy;
assert.equal(ui.safeURL('javascript:alert(1)'), '');
assert.equal(ui.safeURL('https://user:pass@example.com'), '');
const question={id:'q1',prompt:'<img src=x onerror=alert(1)>',options:['a','b','c','<script>x</script>']};
const quiz=ui.quizHTML([question]);
assert.doesNotMatch(quiz,/<img|<script>/);
assert.match(quiz,/required/);
assert.equal((quiz.match(/type="radio"/g)||[]).length,4);
const result=ui.resultHTML({score:0,total:1,percent:0,results:[{...question,answer:1,submitted:0,correct:false,explanation_vi:'Because <script>x</script>'}]});
assert.doesNotMatch(result,/<img|<script>/);
assert.match(result,/is-wrong/);
const library={window:{},localStorage:{getItem:()=>'',setItem:()=>{}}};
vm.runInNewContext(fs.readFileSync('static/library.js','utf8'),library);
const picker=library.window.LexiLibrary.levelPicker('A2');
assert.doesNotMatch(picker,/>ALL</);
assert.match(picker,/class="level-all"/);
assert.match(picker,/data-level="A2" aria-pressed="true"/);
assert.equal((picker.match(/class="level-option"/g)||[]).length,7);
console.log('PASS academy HTML escaping, safe dictionary links, quiz forms and compact level picker');
